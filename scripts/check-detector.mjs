import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import ts from "typescript";
import { createHash } from "node:crypto";
const cache = new Map();
function load(file) {
  file = path.resolve(file);
  if (cache.has(file)) return cache.get(file).exports;
  const mod = { exports: {} }; cache.set(file, mod);
  const source = ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const require = id => load((id.startsWith("@/") ? path.resolve(id.slice(2)) : path.resolve(path.dirname(file), id)) + ".ts");
  new Function("require", "module", "exports", source)(require, mod, mod.exports);
  return mod.exports;
}
const { catalog, defaultCurrentBuild } = load("app/data/catalog.ts");
const { parseDetectorReport, initialImportChoices, applyDetectorImport, suggestedPart, detectorCandidates } = load("app/lib/detector.ts");
const { partIdentity, chipName, partAnalysis } = load("app/lib/part-insights.ts");
const { diagnosePc } = load("app/lib/my-pc.ts");
const c = (category, name, specs = {}) => ({ category, name, manufacturer: category === "cpu" ? "AuthenticAMD" : "Unknown", specs });
const data = { kind: "UpgradePCDetector", schemaVersion: 1, detectorVersion: "1.0.0", scannedAt: "2026-09-17T12:00:00Z", components: [c("cpu", "AMD Ryzen 7 5700X 8-Core Processor", { cores: 8, threads: 16 }), c("gpu", "NVIDIA GeForce RTX 3050"), c("memory", "AX4U3200 8GB DDR4", { capacity: 8, modules: 1, memoryType: "DDR4", speed: 3200 }), c("memory", "AX4U3200 8GB DDR4", { capacity: 8, modules: 1, memoryType: "DDR4", speed: 3200 }), c("storage", "KINGSTON SNV3S500G", { capacity: 500, interface: "SCSI" })], warnings: [] };
const report = parseDetectorReport(JSON.stringify(data));
const choices = initialImportChoices(report, catalog);
assert.equal(choices[0].target, "r7-5700x");
assert.equal(suggestedPart(c("cpu", "AMD Ryzen 7 5700X3D 8-Core Processor"), catalog), "r7-5700x3d");
assert.notEqual(suggestedPart(c("cpu", "AMD Ryzen 7 5700G with Radeon Graphics"), catalog), "r7-5700x");
assert.notEqual(suggestedPart(c("cpu", "AMD Ryzen 7 5700 8-Core Processor"), catalog), "r7-5700x");
assert.equal(choices[1].target, "detected", "Windows GPU name must not guess Gainward/VRAM variant");
assert.equal(choices[2].target, "detected");
assert(detectorCandidates(report.components[2], catalog).every(p => p.specs.modules === 1 && p.specs.capacity === 8), "no two-module kit may match one physical module");
const original = structuredClone(defaultCurrentBuild);
assert.throws(() => applyDetectorImport(original, [], report, choices, catalog), /Confirme/);
const selected = choices.map(choice => ({ ...choice, confirmed: true }));
const imported = applyDetectorImport(original, [], report, selected, catalog);
assert.deepEqual(original, defaultCurrentBuild, "import is a preview, not mutation");
for (const category of ["psu", "cooler", "case", "motherboard", "monitor"]) assert.deepEqual(imported.build.parts[category], original.parts[category], `preserve ${category}`);
assert.equal(imported.build.parts.cpu[0], "r7-5700x");
assert.equal(imported.build.parts.memory.length, 2);
assert.equal(imported.customParts.filter(p => p.category === "memory").length, 1, "same physical model may be reused without duplicate custom catalog entries");
const ramParts = imported.build.parts.memory.map(id => imported.customParts.find(p => p.id === id));
assert.equal(ramParts.reduce((total, p) => total + p.specs.capacity, 0), 16);
assert.equal(ramParts.reduce((total, p) => total + p.specs.modules, 0), 2);
const twice = applyDetectorImport(imported.build, imported.customParts, report, selected, catalog);
assert.deepEqual(twice, imported, "reimport must be idempotent for same hardware");
const skipGpu = selected.map((choice, i) => ({ ...choice, include: i !== 1 }));
assert.deepEqual(applyDetectorImport(original, [], report, skipGpu, catalog).build.parts.gpu, original.parts.gpu);
assert.throws(() => applyDetectorImport(original, [], report, selected.map(c => ({ ...c, include: false })), catalog));
assert.throws(() => applyDetectorImport(original, [], report, selected.map((c, i) => i === 0 ? { ...c, target: "rtx5070" } : c), catalog));
assert.throws(() => parseDetectorReport('{"schemaVersion":1}'));
assert.throws(() => parseDetectorReport(JSON.stringify({ ...data, schemaVersion: 99 })));
assert.throws(() => parseDetectorReport(JSON.stringify({ ...data, components: [c("psu", "Fake")]})));
assert.throws(() => parseDetectorReport("x".repeat(1_000_001)));
assert.throws(() => parseDetectorReport(JSON.stringify({ ...data, components: Array(101).fill(data.components[0]) })));
const hostile = parseDetectorReport(JSON.stringify({ ...data, serialNumber: "do-not-store", components: [{ ...data.components[2], serialNumber: "private", specs: { ...data.components[2].specs, password: "private", serial: "private", tdp: 900, modules: 2, capacity: -8 } }] }));
assert(!JSON.stringify(hostile).includes("private"));
assert(!JSON.stringify(hostile).includes("do-not-store"));
assert.equal(hostile.components[0].specs.modules, 1);
assert.equal(hostile.components[0].specs.capacity, undefined);
assert.equal(parseDetectorReport("\uFEFF" + JSON.stringify(data)).components.length, 5);
const multiGpu = parseDetectorReport(JSON.stringify({ ...data, components: [c("gpu", "Intel UHD Graphics"), c("gpu", "NVIDIA GeForce RTX 3050")] }));
const gpuChoices = initialImportChoices(multiGpu, catalog).map(choice => ({ ...choice, confirmed: true }));
assert.throws(() => applyDetectorImport(original, [], multiGpu, gpuChoices, catalog), /principal/);
const withPrimary = applyDetectorImport(original, [], multiGpu, gpuChoices.map((choice, i) => ({ ...choice, primaryGpu: i === 1 })), catalog);
assert.equal(withPrimary.customParts.find(p => p.id === withPrimary.build.parts.gpu[0]).name, "NVIDIA GeForce RTX 3050");
assert.equal(diagnosePc(imported.build, [...catalog, ...imported.customParts]).find(c => c.id === "gpu-length").status, "pending");

const base = catalog.find(p => p.id === "rx9060xt-16"), variant = catalog.find(p => p.id === "sapphire-pulse-rx9060xt-16");
assert.equal(partIdentity(base).family, partIdentity(variant).family);
assert.equal(partIdentity(base).isModel, false);
assert.equal(partIdentity(variant).isModel, true);
assert.notEqual(partIdentity(variant).family, partIdentity({ ...variant, specs: { ...variant.specs, vram: 8 } }).family);
assert.equal(chipName({ ...variant, name: "Radeon RX 7900 XTX 24GB" }), "RX 7900 XTX");
for (const part of catalog) { const analysis = partAnalysis(part); assert(analysis.strengths.length && analysis.cautions.length && analysis.performance && analysis.audience); }

